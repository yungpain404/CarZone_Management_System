    maNV VARCHAR(10) NOT NULL,
    cheDoTruyCap VARCHAR(20) NOT NULL,
    ngayCapNhat DATETIME2(0) NOT NULL CONSTRAINT DF_CauHinhQuyenTaiKhoan_ngayCapNhat DEFAULT (SYSDATETIME()),
    CONSTRAINT PK_CauHinhQuyenTaiKhoan PRIMARY KEY (maNV),
    CONSTRAINT FK_CauHinhQuyenTaiKhoan_TaiKhoan FOREIGN KEY (maNV) REFERENCES TaiKhoan(maNV) ON DELETE CASCADE,
